export type CopyKey = keyof typeof ui.en;

const WEEKDAY_KEYS = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'] as const satisfies readonly CopyKey[];

export function weekdayLabel(language: Language, weekday: number): string {
  return translate(language, WEEKDAY_KEYS[weekday] ?? 'day');
}

export function translate(language: Language, key: CopyKey, vars?: Vars): string {
  const template = ui[language][key] ?? ui.en[key];
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(vars[name] ?? ''));
}

export type Country = 'PK' | 'IN' | null;

export function languagesForCountry(country: Country): Language[] {
  if (country === 'PK') return ['en', 'ur'];
  if (country === 'IN') return ['en', 'hi'];
  return ['en', 'hi', 'ur'];
}

export function isLanguage(value: string | null | undefined): value is Language {
  return value === 'en' || value === 'hi' || value === 'ur';
}

