export function exerciseCopy(
  language: Language,
  exercise: { id: string; name: string; equipment: string; cue: string; coachNote: string },
): ExerciseCopy {
  if (language === 'en') {
    return { name: exercise.name, equipment: exercise.equipment, cue: exercise.cue, coachNote: exercise.coachNote };
  }
  return exercises[language][exercise.id] ?? {
    name: exercise.name,
    equipment: exercise.equipment,
    cue: exercise.cue,
    coachNote: exercise.coachNote,
  };
}

const KINDS = { Run: 'run', Bike: 'bike', Row: 'row', Walk: 'walk' } as const;

export function cardioKindLabel(language: Language, kind: string): string {
  const key = KINDS[kind as keyof typeof KINDS];
  return key ? translate(language, key) : kind;
}
